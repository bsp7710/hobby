            var list = new List<Page>();
            using (var sr = new StreamReader(Assembly.GetExecutingAssembly().GetManifestResourceStream("manuscript"), Encoding.UTF8))
            {
                string ln;
                while ((ln = sr.ReadLine()) != null)
                {
                    if (ln.Length == 0 || ln[0] == '#')
                        continue;
                    var s = ln.Split('|');
                    var p = new Page
                    {
                        title = s[0],
                        theme = int.Parse(s[1]),
                        intro = s[2],
                        panel = s[6],
                        door = s[7],
                        game = Games[list.Count]
                    };
                    for (int j = 0; j < 3; j++)
                    {
                        var pair = s[3 + j].Split('~');
                        p.items[j] = pair[0];
                        p.notes[j] = pair[1];
                    }

                    list.Add(p);
                }
